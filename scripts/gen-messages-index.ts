/**
 * Generates messages/index.ts — a static map of lazy imports for every
 * locale × namespace JSON file. Static paths keep bundlers happy and make
 * missing files a build error instead of a runtime surprise.
 *
 *   npx tsx scripts/gen-messages-index.ts
 */
import { readdirSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = path.resolve("messages");
const locales = ["de", "en", "fr", "es", "it", "nl", "pl", "pt"];
const namespaces = readdirSync(path.join(root, "en"))
  .filter((f) => f.endsWith(".json"))
  .map((f) => f.replace(/\.json$/, ""))
  .sort();

const lines = [
  "// AUTO-GENERATED by scripts/gen-messages-index.ts — do not edit by hand.",
  "/* eslint-disable */",
  `export const NAMESPACES = ${JSON.stringify(namespaces)} as const;`,
  "export type Namespace = (typeof NAMESPACES)[number];",
  "type Loader = () => Promise<Record<string, unknown>>;",
  "export const loaders: Record<string, Record<Namespace, Loader>> = {",
];
for (const l of locales) {
  lines.push(`  ${l}: {`);
  for (const ns of namespaces) lines.push(`    ${JSON.stringify(ns)}: () => import("./${l}/${ns}.json").then((m) => m.default as Record<string, unknown>),`);
  lines.push("  },");
}
lines.push("};", "");
writeFileSync(path.join(root, "index.ts"), lines.join("\n"));
console.log(`✓ messages/index.ts — ${locales.length} locales × ${namespaces.length} namespaces`);
